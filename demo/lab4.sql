-- Показываем, что ошибка внутри транзакции приводит к отмене всех её изменений.
-- Используем заявку №1. Её исходное состояние после проверки сохранится.


-- 1. Запоминаем исходное состояние заявки
-- expect: rows
-- Показываем номер, приоритет и статус заявки. Результат понадобится для сравнения после отката
SELECT id, priority, status
FROM tickets
WHERE id = 1;


-- 2. Демонстрируем откат всей транзакции
BEGIN;  -- BEGIN начинает транзакцию. Следующие изменения образуют одну группу операций
-- Сначала выполняем допустимое изменение
UPDATE tickets
SET priority = CASE  -- CASE выбирает приоритет, отличный от текущего, но остающийся в разрешённом диапазоне от 1 до 3
    WHEN priority = 3 THEN 2
    ELSE 3
END
WHERE id = 1;
-- Теперь намеренно выполняем ошибочное изменение
-- expect: error check
-- CHECK запрещает приоритет 99
-- После ошибки вся текущая транзакция переходит в состояние отмены
UPDATE tickets
SET priority = 99
WHERE id = 1;
COMMIT;  -- обычно сохраняет изменения, но после ошибки PostgreSQL завершает эту транзакцию откатом (ROLLBACK)


-- 3. Проверяем, что данные не изменились
-- expect: same 1
-- Сравниваем результат с первым шагом. Если приоритет и статус прежние, значит, первое изменение тоже отменилось
SELECT id, priority, status
FROM tickets
WHERE id = 1;


-- 4. Намеренно выполняем неправильное изменение
-- expect: error check
-- В нашей базе разрешены приоритеты только от 1 до 3. Значение 99 нарушает ограничение CHECK
-- PostgreSQL должен выдать ошибку. После ошибки текущая транзакция становится прерванной и не может быть успешно зафиксирована
UPDATE tickets
SET priority = 99
WHERE id = 1;


-- 5. Пытаемся завершить транзакцию
-- Обычно COMMIT сохраняет изменения, но поскольку внутри транзакции произошла ошибка, PostgreSQL завершит её откатом
-- В результате даже допустимое изменение из шага 3 не должно сохраниться
COMMIT;


-- 6. Проверяем состояние заявки ПОСЛЕ транзакции
-- expect: same 1
-- Ожидаем те же значения, что и на шаге 1
-- Это доказывает, что изменение приоритета из шага 3 было отменено вместе со всей транзакцией
SELECT id, priority, status
FROM tickets
WHERE id = 1;


-- 7. Проверяем права роли app_reader
-- SET ROLE временно переключает активную роль. При этом мы остаёмся в том же подключении
SET ROLE app_reader;  -- app_reader должна иметь право читать представления, но не должна получать прямой доступ к таблицам


-- 8. Читатель получает информацию из представления
-- expect: rows
SELECT *   -- SELECT запрашивает данные...
FROM v_ticket_info  -- ...v_ticket_info - представление из ЛР №3. Разрешили app_reader выполнять здесь SELECT командой GRANT
LIMIT 3;  -- ограничивает результат тремя строками


-- 9. Читатель пытается обратиться к таблице
-- expect: error permission
-- Прямое чтение tickets запрещено
-- PostgreSQL должен вернуть permission denied. Это ожидаемая ошибка, а не неисправность базы
SELECT *
FROM tickets
LIMIT 3;


-- 10. Возвращаем исходную роль
RESET ROLE;  -- отменяет действие SET ROLE
-- Следующие команды снова выполняются с первоначальной ролью подключения


-- 11. Переключаемся на роль app_writer
SET ROLE app_writer;  -- app_writer имеет права читателя, а также разрешение вызывать защищённые функции из ЛР №4


-- 12. Проверяем, что прямое изменение запрещено
-- expect: error permission
-- Роль app_writer не должна самостоятельно изменять таблицу tickets
-- Даже допустимый UPDATE обязан завершиться ошибкой из-за недостатка прав
UPDATE tickets
SET priority = 3
WHERE id = 1;


-- 13. Проверяем вызов разрешённой функции
-- Начинаем транзакцию, чтобы после проверки отменить изменение статуса заявки
-- Это важно: тест не должен оставлять заявку №1 закрытой
BEGIN;


-- 14. Закрываем заявку через бизнес-функцию
-- expect: value 1
SELECT safe_close_ticket(1);
-- safe_close_ticket() имеет SECURITY DEFINER, поэтому она может выполнять разрешённую операцию с правами владельца функции
-- Триггер ЛР №3 по-прежнему проверяет наличие ответа сотрудника
-- Ожидаемый результат — ID заявки: 1


-- 15. Отменяем тестовое изменение
ROLLBACK;  -- отменяет закрытие заявки, исходный статус сохраняется


-- 16. Возвращаем исходную роль
RESET ROLE;


-- 17. Проверяем окончательное состояние заявки
-- expect: rows
-- После ROLLBACK заявка должна остаться в том же состоянии, что и до проверки
SELECT id, status, priority
FROM tickets
WHERE id = 1;