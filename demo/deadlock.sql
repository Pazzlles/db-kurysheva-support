
-- Лабораторная работа №4. Дополнительное задание ★
-- Демонстрация взаимоблокировки (deadlock)
--
-- Используем две тестовые заявки.
--
-- Окно A сначала блокирует первую заявку.
-- Окно B сначала блокирует вторую заявку.
--
-- Затем каждое окно пытается изменить заявку,
-- которую уже заблокировало другое окно.
--
-- В результате возникает взаимоблокировка.
-- PostgreSQL должен обнаружить её
-- и отменить одну из транзакций.


-- [setup] Создаём две тестовые заявки.

-- Удаляем остатки предыдущего запуска.
DELETE FROM tickets
WHERE title IN (
    'deadlock-test-1',
    'deadlock-test-2'
);

-- Добавляем две отдельные заявки.
-- Они нужны только для демонстрации блокировок.
INSERT INTO tickets (
    client_id,
    employee_id,
    category_id,
    title,
    description,
    status,
    priority
)
VALUES
(
    1, 1, 1,
    'deadlock-test-1',
    'Первая заявка для проверки deadlock',
    'in_progress', 2
),
(
    1, 1, 1,
    'deadlock-test-2',
    'Вторая заявка для проверки deadlock',
    'in_progress', 2
);


-- [A] Начинаем первую транзакцию.
BEGIN;


-- [A] Блокируем первую заявку.

-- UPDATE изменяет приоритет первой заявки.
-- PostgreSQL блокирует изменяемую строку
-- до завершения транзакции окна A.

UPDATE tickets
SET priority = 3
WHERE title = 'deadlock-test-1';


-- [B] Начинаем вторую транзакцию.
BEGIN;


-- [B] Блокируем вторую заявку.

-- Окно B меняет другую строку.
-- Поэтому пока оба UPDATE выполняются успешно.

UPDATE tickets
SET priority = 3
WHERE title = 'deadlock-test-2';


-- [A] Пытаемся изменить вторую заявку.
-- expect: blocked

-- Вторая заявка уже заблокирована окном B.
-- Поэтому окно A должно ожидать освобождения строки.

UPDATE tickets
SET priority = 1
WHERE title = 'deadlock-test-2';


-- [B] Пытаемся изменить первую заявку.
-- expect: error deadlock

-- Первая заявка заблокирована окном A.
--
-- Возникает замкнутое ожидание:
-- окно A ждёт окно B;
-- окно B ждёт окно A.
--
-- PostgreSQL обнаруживает взаимоблокировку.
-- Ожидаем ошибку с кодом 40P01.

UPDATE tickets
SET priority = 1
WHERE title = 'deadlock-test-1';


-- [B] Завершаем прерванную транзакцию.

-- После ошибки deadlock транзакция окна B
-- должна быть отменена.

ROLLBACK;


-- [A] Завершаем первую транзакцию.

-- После отмены транзакции B её блокировки
-- освобождаются, и окно A может продолжить работу.

COMMIT;


-- [check] Проверяем итоговое состояние.
-- expect: true

-- Первая заявка должна иметь приоритет 3,
-- а вторая — приоритет 1.
--
-- Это изменения транзакции A.
-- Изменения транзакции B должны быть отменены.

SELECT
    (
        SELECT priority = 3
        FROM tickets
        WHERE title = 'deadlock-test-1'
    )
    AND
    (
        SELECT priority = 1
        FROM tickets
        WHERE title = 'deadlock-test-2'
    );


-- [cleanup] Удаляем тестовые заявки.

-- После проверки очищаем тестовые данные.
-- Другие заявки службы поддержки не затрагиваем.

DELETE FROM tickets
WHERE title IN (
    'deadlock-test-1',
    'deadlock-test-2'
);