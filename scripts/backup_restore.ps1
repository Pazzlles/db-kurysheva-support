
# Лабораторная работа №4. Резервное копирование PostgreSQL
# Тема №19: Служба поддержки
#
# Задача:
# Создать резервную копию базы данных app.
# Восстановить её в отдельную пустую базу.
# Проверить, что количество заявок совпадает.
#
# Исходную базу app не удаляем и не изменяем.
# Пароли в этом скрипте не хранятся.


# 1. Основные настройки

# Имя исходной базы данных.
$sourceDb = "app"

# Имя новой базы для восстановления.
# Если база с таким именем уже существует,
# нужно указать другое имя.
$restoreDb = "app_restore_lab4_new"

# Имя файла резервной копии на компьютере.
$backupFile = "lab4_backup.dump"

# Путь к копии внутри контейнера Docker.
$containerFile = "/tmp/lab4_backup.dump"


# 2. Проверяем, запущен ли контейнер PostgreSQL

# docker compose ps -q db получает идентификатор
# контейнера, в котором работает PostgreSQL.
$containerId = docker compose ps -q db

# LASTEXITCODE показывает код завершения команды.
# 0 означает, что команда выполнилась успешно.
# -ne 0 означает, что произошла ошибка.
# -not означает логическое отрицание.

if ($LASTEXITCODE -ne 0 -or -not $containerId) {
    throw "Контейнер PostgreSQL не запущен."
}


# 3. Создаём резервную копию базы данных

# pg_dump — программа PostgreSQL для создания копии.
# -U postgres — подключаемся от пользователя postgres.
# -d — выбираем исходную базу данных.
# -Fc — сохраняем в специальном формате PostgreSQL.
# -f — указываем путь для сохранения файла.
#
# Символ ` в конце строки продолжает команду
# на следующей строке PowerShell.

docker compose exec -T db pg_dump `
    -U postgres `
    -d $sourceDb `
    -Fc `
    -f $containerFile

# Проверяем, успешно ли создалась копия.
# throw выводит сообщение и останавливает скрипт.

if ($LASTEXITCODE -ne 0) {
    throw "Не удалось создать резервную копию."
}


# 4. Копируем резервную копию на компьютер

# docker cp копирует файл из контейнера Docker.
# Сначала указываем контейнер и путь внутри него.
# Затем путь для сохранения на компьютере.
#
# Файлы *.dump исключены из Git через .gitignore.

docker cp "${containerId}:${containerFile}" ".\$backupFile"

if ($LASTEXITCODE -ne 0) {
    throw "Не удалось скопировать резервную копию."
}


# 5. Проверяем, существует ли база для восстановления

# SELECT 1 возвращает число 1, если база существует.
# Если такой базы нет, запрос не возвращает строк.
#
# -tA убирает лишнее оформление вывода psql.
# -c выполняет указанный SQL-запрос.

$exists = docker compose exec -T db psql `
    -U postgres `
    -d postgres `
    -tAc "SELECT 1 FROM pg_database WHERE datname = '$restoreDb';"

if ($LASTEXITCODE -ne 0) {
    throw "Не удалось проверить наличие базы данных."
}

# Преобразуем результат в строку.
# Это предотвращает ошибку, если SELECT ничего не вернул.
#
# Trim() удаляет лишние пробелы.
# -eq означает «равно».

if ("$exists".Trim() -eq "1") {
    throw "База $restoreDb уже существует. Укажи другое имя."
}


# 6. Создаём новую пустую базу данных

# createdb создаёт новую базу PostgreSQL.
# Восстанавливать копию будем именно в неё.
#
# Исходная база app не затрагивается.

docker compose exec -T db createdb `
    -U postgres `
    $restoreDb

if ($LASTEXITCODE -ne 0) {
    throw "Не удалось создать базу для восстановления."
}


# 7. Восстанавливаем данные из резервной копии

# pg_restore — программа восстановления базы.
#
# -d указывает целевую базу данных.
# --no-owner не восстанавливает исходных владельцев.
# --no-acl не восстанавливает отдельные права доступа.
#
# Таблицы, данные и другие объекты из копии
# восстанавливаются в новую базу.

docker compose exec -T db pg_restore `
    -U postgres `
    -d $restoreDb `
    --no-owner `
    --no-acl `
    $containerFile

if ($LASTEXITCODE -ne 0) {
    throw "Восстановление базы завершилось с ошибкой."
}


# 8. Подсчитываем заявки в исходной базе

# SELECT COUNT(*) возвращает количество записей.
# В нашей базе основная таблица называется tickets.

$sourceCount = docker compose exec -T db psql `
    -U postgres `
    -d $sourceDb `
    -tAc "SELECT COUNT(*) FROM tickets;"

if ($LASTEXITCODE -ne 0) {
    throw "Не удалось проверить исходную базу."
}


# 9. Подсчитываем заявки в восстановленной базе

# Выполняем аналогичный запрос,
# но уже в новой базе данных.

$restoreCount = docker compose exec -T db psql `
    -U postgres `
    -d $restoreDb `
    -tAc "SELECT COUNT(*) FROM tickets;"

if ($LASTEXITCODE -ne 0) {
    throw "Не удалось проверить восстановленную базу."
}


# 10. Показываем результаты пользователю

# Write-Host выводит сообщение в терминал.
#
# Перевод английских сообщений предыдущей версии:
# Source tickets — заявок в исходной базе.
# Restored tickets — заявок в восстановленной базе.

Write-Host "Заявок в исходной базе: $sourceCount"
Write-Host "Заявок в восстановленной базе: $restoreCount"


# 11. Сравниваем количество заявок

# -ne означает «не равно».
# Если значения различаются, выводим ошибку.
#
# Это простая проверка восстановления данных.
# Она не гарантирует совпадение абсолютно всех данных,
# поэтому при необходимости проверяются и другие таблицы.

if ("$sourceCount".Trim() -ne "$restoreCount".Trim()) {
    throw "Количество заявок не совпадает."
}


# 12. Сообщаем об успешном завершении

# Перевод прежнего английского сообщения:
# Backup and restore completed successfully —
# резервное копирование и восстановление
# успешно завершены.

Write-Host "Резервное копирование и восстановление выполнены успешно."